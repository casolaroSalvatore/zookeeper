    // T3, testConfig_DuplicateLeftFlag_DeterministicParserBehavior
    // Robustness test for an unspecified duplicate-option scenario
    @Test
    public void testConfig_DuplicateLeftFlag_DeterministicParserBehavior() throws Exception {
        assertCoreAssets();
        assertAssetExists(RIGHT_IDENTICAL);
        String[] arguments = args("-l", LEFT, "-l", RIGHT_IDENTICAL, "-r", RIGHT_PLUS_1, "-b", "0", "-n", "0");
        RunResult firstResult = runSnapshotComparer(arguments);
        RunResult secondResult = runSnapshotComparer(arguments);
        assertEquals("Repeated executions must have the same exit behavior", firstResult.exitStatus, secondResult.exitStatus);
        assertEquals("Repeated executions must have the same exception behavior", throwableType(firstResult.throwable), throwableType(secondResult.throwable));
        assertEquals("Repeated executions must have the same semantic behavior", semanticOutput(firstResult.output), semanticOutput(secondResult.output));
        boolean controlledFailure = isFailedExecution(firstResult);
        boolean controlledCompletion = firstResult.exitStatus == null && firstResult.throwable == null && firstResult.output.contains("All layers compared");
        assertTrue("Duplicate-option behavior must be controlled", controlledFailure || controlledCompletion);
    }

