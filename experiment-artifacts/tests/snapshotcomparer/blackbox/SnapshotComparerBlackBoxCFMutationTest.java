    // Asserts that the console output contains a specific case-insensitive string.
    private static void assertOutputContains(RunResult result, String needle) {
        String normalizedOutput = result.output.toLowerCase(Locale.ROOT);
        String normalizedNeedle = needle.toLowerCase(Locale.ROOT);
        assertTrue("Expected output to contain: " + needle + "\nActual output:\n" + result.output, normalizedOutput.contains(normalizedNeedle));
    }

    // Asserts that the console output contains at least one of the provided case-insensitive strings.
    private static void assertOutputContainsAny(RunResult result, String... needles) {
        String executionText = observableText(result);
        String normalized = executionText.toLowerCase(Locale.ROOT);
        for (String needle : needles) {
            if (normalized.contains(needle.toLowerCase(Locale.ROOT))) {
                return;
            }
        }
        fail("Expected execution result to contain one of " + Arrays.toString(needles) + "\nActual execution result:\n" + executionText);
    }

    // Asserts that the console output does NOT contain a specific case-insensitive string.
    private static void assertOutputDoesNotContain(RunResult result, String needle) {
        String normalizedOutput = result.output.toLowerCase(Locale.ROOT);
        String normalizedNeedle = needle.toLowerCase(Locale.ROOT);
        assertFalse("Output must not contain: " + needle + "\nActual output:\n" + result.output, normalizedOutput.contains(normalizedNeedle));
    }

    // Asserts that the console output does NOT contain any of the provided case-insensitive strings.
    private static void assertOutputDoesNotContainAny(RunResult result, String... needles) {
        for (String needle : needles) {
            assertOutputDoesNotContain(result, needle);
        }
    }

    // Asserts that the execution failed through either a non-zero exit request or a propagated exception.
    private static void assertFailed(RunResult result) {
        assertTrue("Invalid input must cause either a non-zero exit request " + "or an exception. Output:\n" + observableText(result), isFailedExecution(result));
    }

    private static boolean isFailedExecution(RunResult result) {
        boolean nonZeroExit = result.exitStatus != null && result.exitStatus.intValue() != 0;
        return nonZeroExit || result.throwable != null;
    }

    private static String throwableType(Throwable throwable) {
        return throwable == null ? "" : throwable.getClass().getName();
    }

    private static String observableText(RunResult result) {
        StringBuilder text = new StringBuilder(result.output);
        Throwable current = result.throwable;
        while (current != null) {
            text.append(System.lineSeparator()).append(current.getClass().getName());
            if (current.getMessage() != null) {
                text.append(": ").append(current.getMessage());
            }
            current = current.getCause();
        }
        return text.toString();
    }

    // Asserts that no quantitative delta information is printed for the specified node path.
    private static void assertNoQuantitativeDeltaForPath(RunResult result, String path) {

        for (String line : result.output.split("\\R")) {
            boolean reportsPath = line.contains("Node " + path + " ");

            boolean reportsDifference = line.contains("Delta:") || line.contains("found only in left tree") || line.contains("found only in right tree");

            assertFalse("No difference must be reported for " + path + ". Unexpected line: " + line, reportsPath && reportsDifference);
        }
    }

    // Asserts that a specific quantitative delta is printed for the specified node path.
    private static void assertQuantitativeDeltaForPath(RunResult result, String path, String expectedDelta) {
        assertOutputContains(result, "Node " + path + " found in both trees. Delta: " + expectedDelta);
    }

    // Constructs an input string for interactive mode. The interactive mode uses a while(currentDepth < maxDepth) loop,
    // calling Scanner.nextLine() on each iteration. If it is only sent a single command (e.g., "/node\n"), the next
    // iteration will throw NoSuchElementException because the simulated input stream is exhausted.
    // By appending multiple newlines, we allow the loop to safely advance and exit gracefully.
    private static String interactiveInput(String command, int trailingNewlines) {
        StringBuilder input = new StringBuilder(command).append('\n');
        for (int index = 0; index < trailingNewlines; index++) {
            input.append('\n');
        }
        return input.toString();
    }

    // Filters the raw output to retain only semantically meaningful lines. ZooKeeper prints many infrastructural
    // logs on startup (e.g., JVM memory stats, timestamps, environment variables).
    // To reliably compare outputs across different executions (e.g. testing flag duplication),
    // we strip away this "noise" and keep only the business logic lines printed directly by the SUT's algorithm.
    private static String semanticOutput(String output) {
        StringBuilder semantic = new StringBuilder();
        for (String line : output.replace("\r\n", "\n").split("\n")) {
            String trimmed = line.trim();
            String normalizedTrimmed = trimmed.toLowerCase(Locale.ROOT);
            if (trimmed.startsWith("Node count:") || trimmed.startsWith("Total size:") || trimmed.startsWith("Max depth:") || trimmed.startsWith("Count of nodes at depth") || trimmed.startsWith("Node ") || trimmed.startsWith("Filtered node ") || trimmed.startsWith("Analysis for depth") || trimmed.startsWith("All layers compared") || trimmed.startsWith("Usage:") || normalizedTrimmed.contains("unrecognized option") || normalizedTrimmed.contains("missing argument")) {
                semantic.append(trimmed).append('\n');
            }
        }
        return semantic.toString().trim();
    }

    // Container class to hold the captured console output and the exit status of the executed process.
    private static final class RunResult {
        final String output;
        final Throwable throwable;
        final Integer exitStatus;
        RunResult(String output, Throwable throwable, Integer exitStatus) {
            this.output = output;
            this.throwable = throwable;
            this.exitStatus = exitStatus;
        }
    }

    // Internal control-flow exception used only to intercept ZooKeeper's exit
    // request without terminating the JUnit JVM.
    private static final class ExitException extends RuntimeException {
        private static final long serialVersionUID = 1L;
        final int status;
        ExitException(int status) {
            super("ServiceUtils.requestSystemExit(" + status + ") intercepted during black-box execution");
            this.status = status;
        }
    }

    // ADDED IN ORDER TO IMPROVE METRICS
    private static int countOccurrencesIgnoreCase(String text, String fragment) {

        String normalizedText = text.toLowerCase(Locale.ROOT);
        String normalizedFragment = fragment.toLowerCase(Locale.ROOT);

        int count = 0;
        int index = 0;

        while ((index = normalizedText.indexOf(normalizedFragment, index)) >= 0) {
            count++;
            index += normalizedFragment.length();
        }
        return count;
    }

    // Extracts the portion of captured output between two markers. The start marker is excluded
    // from the returned value. If the end marker is not found, the section extends to the end
    // of the captured output.
    private static String outputSection(RunResult result, String startMarker, String endMarker) {

        String output = result.output;
        int start = output.indexOf(startMarker);

        assertTrue("Start marker not found: " + startMarker + "\nActual output:\n" + output,
                start >= 0);

        int contentStart = start + startMarker.length();
        int end = output.indexOf(endMarker, contentStart);

        if (end < 0) {
            end = output.length();
        }

        return output.substring(contentStart, end);
    }
