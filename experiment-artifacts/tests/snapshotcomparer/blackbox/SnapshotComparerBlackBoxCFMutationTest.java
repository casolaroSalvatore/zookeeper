    // Executes the SnapshotComparer CLI with the given arguments and no standard input.
    private RunResult runSnapshotComparer(String[] arguments) throws Exception {
        return runSnapshotComparer(arguments, null);
    }

    // Executes SnapshotComparer.main() in the current JUnit JVM.
    // The method is synchronized because System.in, System.out, System.err and the ServiceUtils exit procedure
    // are global JVM state. Serializing calls prevents concurrent tests from replacing each other's streams or exit
    // callbacks.
    private static synchronized RunResult runSnapshotComparer(String[] arguments, String stdin) throws Exception {
        PrintStream originalOut = System.out;
        PrintStream originalErr = System.err;
        InputStream originalIn = System.in;
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ByteArrayOutputStream err = new ByteArrayOutputStream();
        PrintStream capturedOut = new PrintStream(out, true, StandardCharsets.UTF_8.name());
        PrintStream capturedErr = new PrintStream(err, true, StandardCharsets.UTF_8.name());
        try {
            System.setOut(capturedOut);
            System.setErr(capturedErr);
            if (stdin != null) {
                System.setIn(new ByteArrayInputStream(stdin.getBytes(StandardCharsets.UTF_8)));
            }
            // SnapshotComparer invokes ServiceUtils.requestSystemExit() for CLI
            // parsing failures. Replacing ZooKeeper's exit callback converts that
            // request into an exception observable by the test without terminating
            // the JUnit JVM.
            ServiceUtils.setSystemExitProcedure(status -> { throw new ExitException(status); });
            try {
                SnapshotComparer.main(arguments);
                return new RunResult(capturedOutput(out, err), null, null);
            } catch (ExitException exit) {
                // A requested exit is represented only through exitStatus.
                // It is not also classified as an unexpected throwable.
                return new RunResult(capturedOutput(out, err), null, exit.status);
            } catch (Exception exception) {
                // Deserialization and numeric-conversion failures may propagate
                // directly instead of requesting process termination.
                return new RunResult(capturedOutput(out, err), exception, null);
            }
        } finally {
            capturedOut.flush();
            capturedErr.flush();
            System.setOut(originalOut);
            System.setErr(originalErr);
            System.setIn(originalIn);
            // Restore ZooKeeper's documented default termination strategy.
            ServiceUtils.setSystemExitProcedure(ServiceUtils.SYSTEM_EXIT);
            capturedOut.close();
            capturedErr.close();
        }
    }

    private static String capturedOutput(ByteArrayOutputStream out, ByteArrayOutputStream err) throws Exception {
        System.out.flush();
        System.err.flush();
        return out.toString(StandardCharsets.UTF_8.name()) + System.lineSeparator() + err.toString(StandardCharsets.UTF_8.name());
    }

